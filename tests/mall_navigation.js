const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const storage = {};
const actions = [];
const uni = { setStorageSync: (key, value) => { storage[key] = value; }, getStorageSync: key => storage[key],
  removeStorageSync: key => { delete storage[key]; }, switchTab: value => actions.push(value.url), redirectTo: value => actions.push(value.url) };
const context = { module: { exports: {} }, uni, Date, Number };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../utils/mallNavigation.js'), 'utf8').replace('export default', 'module.exports ='), context);
const N = context.module.exports;
N.openCardMall({ source: 'ticket_checkout', targetType: 1, amount: 99, returnToCheckout: true,
  returnUrl: '/pages/ticket/buy?count=3', returnDraft: { ticketCount: 3 } });
assert.strictEqual(actions.pop(), '/pages/voucher/voucher');
const intent = N.takeCardIntent();
assert.strictEqual(intent.source, 'ticket_checkout');
assert.strictEqual(intent.targetType, 1);
assert(intent.returnUrl.startsWith('/pages/ticket/buy?count=3&mall_return_id='));
assert(intent.returnId);
assert.strictEqual(N.takeCardIntent(), null);
assert(N.confirmationUrl('card/?中文', intent).includes('card_id=card%2F%3F%E4%B8%AD%E6%96%87'));
N.openCardMall(intent);
N.takeCardIntent();
assert.strictEqual(N.resumeCheckout(intent), true);
assert.strictEqual(actions.pop(), intent.returnUrl);
assert.strictEqual(N.takeCheckoutDraft('wrong', intent.returnId), null);
assert.strictEqual(N.takeCheckoutDraft('ticket_checkout'), null);
assert.strictEqual(N.takeCheckoutDraft('ticket_checkout', 'wrong-return'), null);
assert.strictEqual(N.takeCheckoutDraft('ticket_checkout', intent.returnId).ticketCount, 3);
assert.strictEqual(N.takeCheckoutDraft('ticket_checkout'), null);
assert.strictEqual(N.resumeCheckout({ source: 'home_saver', returnUrl: '/pages/order/createOrder' }), false);
['toString', '__proto__', 'constructor'].forEach(source => assert.strictEqual(N.resumeCheckout({ source }), false));
N.openCardMall({ source: 'room_checkout', targetType: 2, returnToCheckout: true, returnUrl: 'https://untrusted.example' });
const safe = N.takeCardIntent();
assert.strictEqual(safe.returnUrl, '/pages/order/createOrder');
N.openCardMall({ source: 'room_checkout', returnToCheckout: true, returnDraft: { numOfPeople: 2 } });
N.openCardMall({ source: 'user_center' });
assert.strictEqual(N.takeCheckoutDraft('room_checkout'), null);
N.openCardMall({ source: 'room_checkout', targetType: 42, amount: NaN });
const normal = N.takeCardIntent();
assert.strictEqual(normal.targetType, 0);
assert.strictEqual(normal.amount, 0);
assert.strictEqual(normal.returnToCheckout, false);
storage.mall_card_intent = { source: 'ticket_checkout', createdAt: Date.now() - 31 * 60000 };
assert.strictEqual(N.takeCardIntent(), null);
storage.mall_card_intent = { createdAt: Date.now() + 60000 };
assert.strictEqual(N.takeCardIntent(), null);
storage.mall_card_intent = { createdAt: 'invalid' };
assert.strictEqual(N.takeCardIntent(), null);
const pages = fs.readFileSync(path.join(__dirname, '../pages.json'), 'utf8');
const tabBar = pages.slice(pages.indexOf('"tabBar"'));
assert.strictEqual((tabBar.match(/"pagePath"/g) || []).length, 5);
assert(tabBar.includes('"text": "商城"'));
assert(!tabBar.includes('"text": "卡券"'));
assert(pages.includes('"path": "pages/voucher/claim"'));
assert(pages.includes('"navigationBarTitleText": "卡包详情"'));
console.log('Mall navigation: exact card route, safe checkout return and one-shot volatile drafts passed');
