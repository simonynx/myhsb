const assert=require('assert'),fs=require('fs'),path=require('path'),vm=require('vm');
const context={module:{exports:{}},Date,Number};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../utils/loyaltyPresentation.js'),'utf8').replace('export default','module.exports ='),context);
const L=context.module.exports;
const pure={object_id:'water',name:'矿泉水',goods_type:2,exchange_type:2,points_price:180,price:200,stock:5};
const coupon={object_id:'coupon',name:'复访券',goods_type:5,exchange_type:2,points_price:500,stock:-1,coupon_template_id:'template'};
const mixed={object_id:'mixed',goods_type:2,exchange_type:3,points_price:100,price:250,stock:4};
const user={points:355,member_level:0,points_config:{points_min_use:100,points_step:100,points_max_use:10000,points_to_fen:1}};
const view=L.decorateGoods(pure,user,true);
assert.strictEqual(view.canExchange,true);assert.strictEqual(view.priceText,'180积分');assert(view.deliveryText.includes('门店领取'));
assert.strictEqual(L.decorateGoods(pure,user,false).canExchange,false);
assert(L.decorateGoods(pure,user,false).stateText.includes('登录'));
assert.strictEqual(L.decorateGoods(coupon,user,true).pointsShortfall,145);
assert(L.decorateGoods(coupon,user,true).deliveryText.includes('我的优惠券'));
assert(L.decorateGoods(Object.assign({},pure,{goods_type:5}),user,true).deliveryText.includes('门店领取'));
assert.strictEqual(L.decorateGoods(mixed,user,true).priceText,'100积分 + ¥2.5');
assert(L.decorateGoods(mixed,user,true).stateText.includes('现金'));
assert.strictEqual(L.decorateGoods(Object.assign({},pure,{stock:0}),user,true).canExchange,false);
assert.strictEqual(L.decorateGoods(Object.assign({},pure,{member_level_required:2}),user,true).canExchange,false);
assert.strictEqual(L.decorateGoods(Object.assign({},pure,{max_buy_per_user:1,user_bought_count:1}),user,true).canExchange,false);
const list=L.benefits([mixed,pure,coupon,{exchange_type:1,goods_type:2},{exchange_type:2,goods_type:1}],user,true);
assert.strictEqual(list.length,3);assert.strictEqual(list[0].object_id,'water');assert.strictEqual(list[2].object_id,'mixed');
const points=L.pointsView(user,true);
assert.strictEqual(points.valueText,'按当前规则，最多可抵¥3');
assert(points.usageText.includes('以订单应付金额'));
assert.strictEqual(L.pointsView({points:99,points_config:user.points_config},true).valueText,'');
assert.strictEqual(L.pointsView({points:50000,points_config:user.points_config},true).valueText,'按当前规则，最多可抵¥100');
assert.strictEqual(L.pointsView({points:1000},true).valueText,'');
['points_to_fen','points_min_use','points_step','points_max_use'].forEach(field => {
  const config=Object.assign({},user.points_config);config[field]+=0.5;
  assert.strictEqual(L.pointsView({points:1000,points_config:config},true).valueText,'');
});
assert.strictEqual(L.pointsView(user,false).points,0);assert.strictEqual(L.pointsView(user,false).valueText,'');
assert.strictEqual(L.money(1234),'12.34');assert.strictEqual(L.money(0),'0');
console.log('Loyalty presentation: actual point steps/caps, guest state, mixed cash and coupon association passed');
